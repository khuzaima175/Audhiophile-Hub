const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { ensureViteServer, ensurePreviewServer, launchBrowser } = require('./browserEnv.cjs');

(async () => {
  fs.mkdirSync('artifacts/step3', { recursive: true });
  const dev = await ensureViteServer();
  const preview = await ensurePreviewServer();
  const browser = await launchBrowser(chromium);
  try {
    const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
    page.setDefaultTimeout(10000);
    const errors = [], syncs = [];
    page.on('pageerror', error => errors.push(error.message));
    let permission = true, exists = true, syncSuccess = true;
    await page.route('**/api/apo/status*', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ connected: exists, exists, path: 'C:\\test\\config.txt', hasManagedInclude: true, hasBackup: true }) }));
    await page.route('**/api/apo/test-write', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ success: permission, error: permission ? undefined : 'EACCES: permission denied' }) }));
    await page.route('**/api/apo/sync', route => {
      syncs.push(route.request().postDataJSON());
      return route.fulfill({ contentType: 'application/json', body: JSON.stringify({ success: syncSuccess, error: syncSuccess ? undefined : 'Write failed' }) });
    });
    const navEq = () => page.locator('.workspace-sidebar').getByRole('button', { name: 'Equalizer', exact: false }).click();
    await page.goto('http://127.0.0.1:3000');
    await page.evaluate(() => localStorage.setItem('audiosage_apo_enabled', 'true'));
    await navEq();
    await page.getByRole('button', { name: 'New preset', exact: true }).click();
    await page.getByLabel('Gain at 1000 Hz', { exact: true }).fill('5');
    const apply = page.getByRole('button', { name: 'Apply to Windows', exact: true });
    await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(b => b.textContent === 'Apply to Windows')?.disabled);
    assert.equal(await page.locator('.apo-applied-status').innerText(), 'Applied: unknown');
    await page.getByRole('button', { name: 'Save preset…', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Save EQ preset', exact: true });
    await dialog.getByLabel('Preset name', { exact: true }).fill('Review EQ');
    await page.keyboard.press('Shift+Tab');
    assert.equal(await dialog.getByRole('button', { name: 'Save', exact: true }).evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('Tab');
    assert.equal(await dialog.getByLabel('Preset name', { exact: true }).evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('button', { name: 'Save preset…', exact: true }).evaluate(el => el === document.activeElement), true);
    await page.getByRole('button', { name: 'Save preset…', exact: true }).click();
    await dialog.getByLabel('Preset name', { exact: true }).fill('Review EQ');
    for (const width of [1920, 390, 320]) {
      await page.setViewportSize({ width, height: width === 1920 ? 1080 : 844 });
      await dialog.waitFor();
      const bounds = await dialog.boundingBox();
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width && bounds.y >= 0 && bounds.y + bounds.height <= (width === 1920 ? 1080 : 844));
      assert.ok(await dialog.locator('input, select, button').evaluateAll(els => els.every(el => el.getBoundingClientRect().height >= 44)));
      await page.screenshot({ path: `artifacts/step3/save-preset-dialog-${width}.png` });
    }
    await dialog.getByRole('button', { name: 'Save', exact: true }).click();
    assert.equal(syncs.length, 0, 'Save must never sync, including opted-in users');
    await page.setViewportSize({ width: 1920, height: 1080 });
    await page.getByRole('button', { name: 'Save as copy…', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Save copy', exact: true }).click();
    assert.equal(syncs.length, 0, 'Save copy must never sync');
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('audiosage_profile_v1')).eqLibrary.filter(p => p.name === 'Review EQ').length), 2);
    console.log('PASS fetch spy: Save=0 sync calls; Save copy=0 sync calls with APO opted in');
    await page.evaluate(() => localStorage.setItem('audiosage_apo_enabled', 'false'));
    page.once('dialog', async dialog => {
      assert.match(dialog.message(), /Adds one include line to config.txt, with a backup/);
      await dialog.dismiss();
    });
    await apply.click();
    assert.equal(syncs.length, 0, 'Cancelling first Apply must never sync');
    assert.equal(await page.evaluate(() => localStorage.getItem('audiosage_apo_apply_consent_v1')), null);
    page.once('dialog', async dialog => {
      assert.match(dialog.message(), /affects system audio/);
      await dialog.accept();
    });
    await apply.click();
    await page.waitForFunction(() => document.querySelector('.apo-applied-status')?.textContent === 'Applied: Review EQ');
    assert.equal(syncs.length, 1, 'Apply must sync exactly once');
    assert.match(syncs[0].eqContent, /Preamp: -[\d.]+ dB/);
    assert.match(syncs[0].eqContent, /Filter/);
    assert.equal(await page.evaluate(() => localStorage.getItem('audiosage_apo_enabled')), 'true', 'Successful Apply must reflect the enabled managed include in Settings');
    assert.ok(await page.evaluate(() => localStorage.getItem('audiosage_apo_apply_consent_v1')));
    console.log('PASS first Apply explains config/include/backup; cancel makes zero sync calls; consent persists after successful Apply');
    console.log('PASS fetch spy: Apply=1 sync call with guarded EQ export');
    const applied = await page.evaluate(() => localStorage.getItem('audiosage_apo_applied_state_v1'));
    assert.ok(JSON.parse(applied).signature);
    await page.reload();
    await navEq();
    assert.match(await page.locator('.apo-applied-status').innerText(), /Applied: Review EQ · Windows state unverified after reload/);
    await page.getByLabel('Gain at 1000 Hz', { exact: true }).fill('6');
    assert.match(await page.locator('.apo-applied-status').innerText(), /editor has changed since/);
    syncSuccess = false;
    await apply.click();
    await page.getByText(/Could not apply to Windows: Write failed/).waitFor();
    assert.equal(await page.evaluate(() => localStorage.getItem('audiosage_apo_applied_state_v1')), applied);
    console.log('PASS applied signature/label survive reload; unknown Windows state is explicit; failed Apply preserves last success');
    await page.getByRole('button', { name: 'Back to presets', exact: true }).click();
    const row = page.getByRole('region', { name: 'Unsaved draft', exact: true });
    await row.waitFor();
    await page.reload(); await navEq(); await row.waitFor();
    await row.getByRole('button', { name: 'Resume draft', exact: true }).click();
    assert.equal(await page.getByLabel('Gain at 1000 Hz', { exact: true }).inputValue(), '6');
    await page.getByRole('button', { name: 'Back to presets', exact: true }).click();
    page.once('dialog', d => d.dismiss());
    await row.getByRole('button', { name: 'Discard draft', exact: true }).click();
    await row.waitFor();
    page.once('dialog', d => d.accept());
    await row.getByRole('button', { name: 'Discard draft', exact: true }).click();
    assert.equal(await row.count(), 0);
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('audiosage_profile_v1')).eqLibrary.length), 2);
    console.log('PASS hidden draft resume after reload, discard cancel/confirm, saved presets preserved');
    permission = false;
    await page.reload(); await navEq();
    await page.getByRole('button', { name: 'New preset', exact: true }).click();
    await page.getByText(/Write permission check failed: EACCES/).waitFor();
    assert.equal(await apply.isDisabled(), true);
    exists = false;
    await page.reload(); await navEq();
    await page.getByText(/config.txt not found/).waitFor();
    assert.equal(await apply.isDisabled(), true);
    console.log('PASS local permission denial and missing config are distinct from hosted/unavailable bridge');
    for (const width of [1920, 390]) {
      const hosted = await browser.newPage({ viewport: { width, height: width === 1920 ? 1080 : 844 } });
      hosted.on('pageerror', error => errors.push(error.message));
      await hosted.goto('http://127.0.0.1:3001');
      if (width < 768) await hosted.getByRole('button', { name: 'Open navigation', exact: true }).click();
      await hosted.locator('.workspace-sidebar').filter({ visible: true }).getByRole('button', { name: 'Equalizer', exact: false }).click();
      await hosted.getByRole('button', { name: 'New preset', exact: true }).click();
      await hosted.getByText('Needs a local run on Windows', { exact: true }).waitFor();
      const disabled = hosted.getByRole('button', { name: 'Apply to Windows', exact: true });
      assert.equal(await disabled.isDisabled(), true);
      await disabled.scrollIntoViewIfNeeded();
      assert.ok(await hosted.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await hosted.screenshot({ path: `artifacts/step3/disabled-apply-windows-${width}.png` });
      await hosted.close();
    }
    assert.deepEqual(errors, []);
    console.log('PASS built static preview disabled Apply at 1920px/390px; dialog at 1920px/390px/320px; screenshots saved');
  } finally {
    await browser.close();
    if (dev.spawned) dev.kill();
    if (preview.spawned) preview.kill();
  }
})().catch(error => { console.error(error); process.exit(1); });
