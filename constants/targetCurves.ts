// Logarithmic interpolation helper for target curves
export const getInterpolatedTargetGain = (freq: number, points: CurvePoint[]): number => {
  if (!points || points.length === 0) return 0;
  if (freq <= points[0].freq) return points[0].gain;
  if (freq >= points[points.length - 1].freq) return points[points.length - 1].gain;

  for (let i = 0; i < points.length - 1; i++) {
    const p1 = points[i];
    const p2 = points[i + 1];
    if (freq >= p1.freq && freq <= p2.freq) {
      const logF = Math.log10(freq);
      const logF1 = Math.log10(p1.freq);
      const logF2 = Math.log10(p2.freq);
      const span = logF2 - logF1;
      if (span === 0) return p1.gain;
      const ratio = (logF - logF1) / span;
      return parseFloat((p1.gain + ratio * (p2.gain - p1.gain)).toFixed(2));
    }
  }
  return 0;
};

